// LCD physical address base (matches axi_mux: 0x1fc0xxxx)
#define LCD_PHYS_BASE   0x1fc00000
#define LCD_PHYS_LEN    0x10

#define LCD_CMD_OFF     0x00
#define LCD_DATA_OFF    0x04
#define LCD_STAT_OFF    0x08
#define LCD_CTRL_OFF    0x0C

#define CTRL_RST_N      0x01
#define CTRL_BL_ON      0x02
#define STAT_BUSY       0x01
#define STAT_STARTED    0x04
#define STAT_WR_CNT_SHIFT 16

static volatile unsigned int *lcd_base;

static void lcd_wait_idle(void)
{
    while (lcd_base[LCD_STAT_OFF / 4] & STAT_BUSY)
        ;
}

static void lcd_cmd(unsigned short cmd)
{
    lcd_wait_idle();
    lcd_base[LCD_CMD_OFF / 4] = cmd;
}

static void lcd_data(unsigned short data)
{
    lcd_wait_idle();
    lcd_base[LCD_DATA_OFF / 4] = data;
}

static void delay_us(int us)
{
    usleep(us);
}

