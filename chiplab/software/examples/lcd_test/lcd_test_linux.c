#define INIT_SEQ_LEN (sizeof(lcd_init_data) / sizeof(lcd_init_data[0]))

static void lcd_run_init(void)
{
    printf("LCD: Sending init sequence (%d entries)...\n", INIT_SEQ_LEN);
    for (int i = 0; i < INIT_SEQ_LEN; i++) {
        lcd_cmd(lcd_init_data[i][0]);
        lcd_data(lcd_init_data[i][1]);
    }
    printf("LCD: Init sequence done. Waiting 200ms (Sleep Out delay)...\n");
    delay_us(200000);
}

// Fill screen with color using indexed register format (from reference draw module)
// Display resolution: 800x480 (SC=0..799, SP=0..479)
static void lcd_fill(unsigned short color)
{
    // Set Address Mode (same as reference: 0x3600 + data 0x0020)
    lcd_cmd(0x3600);
    lcd_data(0x0020);

    // Set Column Address (indexed: 0x2A00..0x2A03, matching reference draw module)
    lcd_cmd(0x2A00); lcd_data(0x0000);  // SC[15:8] = 0
    lcd_cmd(0x2A01); lcd_data(0x0000);  // SC[7:0]  = 0
    lcd_cmd(0x2A02); lcd_data(0x0003);  // EC[15:8] = 3 (799 = 0x031F)
    lcd_cmd(0x2A03); lcd_data(0x001F);  // EC[7:0]  = 0x1F

    // Set Page Address (indexed: 0x2B00..0x2B03)
    lcd_cmd(0x2B00); lcd_data(0x0000);  // SP[15:8] = 0
    lcd_cmd(0x2B01); lcd_data(0x0000);  // SP[7:0]  = 0
    lcd_cmd(0x2B02); lcd_data(0x0001);  // EP[15:8] = 1 (479 = 0x01DF)
    lcd_cmd(0x2B03); lcd_data(0x00DF);  // EP[7:0]  = 0xDF

    // Write Memory Start
    lcd_cmd(0x2C00);

    int total = 800 * 480;
    for (int i = 0; i < total; i++) {
        lcd_data(color);
    }
}

int main(void)
{
    unsigned int stat;
    int fd = open("/dev/mem", O_RDWR | O_SYNC);
    if (fd < 0) {
        perror("open /dev/mem");
        printf("Try: sudo chmod 666 /dev/mem  or run as root\n");
        return 1;
    }

    lcd_base = mmap(NULL, LCD_PHYS_LEN, PROT_READ | PROT_WRITE,
                    MAP_SHARED, fd, LCD_PHYS_BASE);
    if (lcd_base == MAP_FAILED) {
        perror("mmap LCD");
        close(fd);
        return 1;
    }

    printf("LCD registers mapped at phys 0x%x\n", LCD_PHYS_BASE);
    stat = lcd_base[LCD_STAT_OFF / 4];
    printf("STAT_REG = 0x%x (started=%u, wr_cnt=%u)\n",
           stat, (stat & STAT_STARTED) ? 1 : 0, (stat >> STAT_WR_CNT_SHIFT) & 0xFFFF);
    printf("CTRL_REG = 0x%x\n", lcd_base[LCD_CTRL_OFF / 4]);

    // Step 1: Hold LCD in reset, backlight on
    printf("Step 1: Backlight ON, LCD in reset\n");
    lcd_base[LCD_CTRL_OFF / 4] = CTRL_BL_ON;
    delay_us(100000);

    // Step 2: Release reset
    printf("Step 2: Releasing reset\n");
    lcd_base[LCD_CTRL_OFF / 4] = CTRL_RST_N | CTRL_BL_ON;
    delay_us(100000);

    // Step 3: Run init sequence from reference design
    lcd_run_init();

    stat = lcd_base[LCD_STAT_OFF / 4];
    printf("After init: STAT=0x%08x, started=%u, wr_cnt=%u\n",
           stat, (stat & STAT_STARTED) ? 1 : 0, (stat >> STAT_WR_CNT_SHIFT) & 0xFFFF);

    // Step 4: Display ON
    printf("Step 4: Display ON (0x2900)\n");
    lcd_cmd(0x2900);
    delay_us(100000);

    // Step 5: Fill screen red
    printf("Step 5: Fill RED (0xF800) on 800x480...\n");
    lcd_fill(0xF800);
    printf("Done!\n");

    stat = lcd_base[LCD_STAT_OFF / 4];
    printf("After fill: STAT=0x%08x, started=%u, wr_cnt=%u\n",
           stat, (stat & STAT_STARTED) ? 1 : 0, (stat >> STAT_WR_CNT_SHIFT) & 0xFFFF);

    munmap((void *)lcd_base, LCD_PHYS_LEN);
    close(fd);
    return 0;
}